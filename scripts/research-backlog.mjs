// Deterministic research backlog; it reports editorial gaps, never credibility scores.
const nativeLanguages={
 'Allemagne':['de','en','fr'],'Autriche':['de','en','fr'],'Suisse':['de','fr','en'],
 'France':['fr','en'],'Belgique':['fr','nl','en'],'États-Unis':['en','fr'],'Royaume-Uni':['en','fr'],
 'Chine':['zh','en','fr'],'Japon':['ja','en','fr'],'Inde':['en','hi','fr'],'Italie':['it','en','fr'],
 'Espagne':['es','en','fr'],'Mexique':['es','en','fr'],'Brésil':['pt','en','fr'],'Russie':['ru','en','fr']
};
const domain=x=>{try{return new URL(x).hostname.replace(/^www\./,'')}catch{return null}};
export const sourceInventory=record=>{
 const urls=[
  ...(record?.sections||[]).map(x=>x.source),...(record?.events||[]).map(x=>x.source),
  ...Object.values(record?.personal||{}).flatMap(xs=>Array.isArray(xs)?xs.map(x=>x.source):[])
 ].filter(Boolean);
 return {uniqueUrls:new Set(urls).size,uniquePublishers:new Set(urls.map(domain).filter(Boolean)).size};
};
const canonical=name=>String(name||'').trim().replace(/\s*& family$/i,'');
export function queryPlan(person){
 const name=canonical(person.name),company=String(person.co||'').split(/[;,]/).map(s=>s.trim()).filter(Boolean)[0]||'';
 const languages=nativeLanguages[person.country]||['en','fr'];
 return {languages,
   queries:[
    '"'+name+'"',
    company?'"'+name+'" "'+company+'"':null,
    '"'+name+'" interview OR career OR biography',
    '"'+name+'" company OR founder OR owner',
    '"'+name+'" site:linkedin.com/in',
    company?'"'+company+'" annual report ownership family shareholders':null,
    '"'+name+'" 2026',
   ].filter(Boolean),
   sourceTargets:['local-language news agencies','official personal and company sites','national business registry','regulator and annual reports','interviews and public statements','cross-language reference sites'],
   restrictions:'Avoid homonyms, unconfirmed private claims, autogenerated source mirrors, and conflating corporate facts with personal wealth.'
 };
}
export function auditProfiles(people,profiles){
 const items=people.map(person=>{
  const record=profiles[person.id]||null;
  const chapters=(record?.sections||[]).length,events=(record?.events||[]).length;
  const source=sourceInventory(record);
  const state=chapters===0?'no_editorial_articles':chapters<4?'thin_dossier':'substantive_dossier';
  return {slug:person.id,name:person.name,country:person.country,wealthSource:person.co||'',
    editorialStatus:state,chapters,events,sourceUrls:source.uniqueUrls,publishers:source.uniquePublishers,
    nextResearch:queryPlan(person)};
 });
 const priority={no_editorial_articles:0,thin_dossier:1,substantive_dossier:2};
 items.sort((a,b)=>priority[a.editorialStatus]-priority[b.editorialStatus]||
  a.publishers-b.publishers||a.chapters-b.chapters||a.name.localeCompare(b.name,'fr'));
 return {generatedAt:new Date().toISOString(),totalProfiles:items.length,statistics:{
   noEditorialArticles:items.filter(i=>i.editorialStatus==='no_editorial_articles').length,
   thinDossiers:items.filter(i=>i.editorialStatus==='thin_dossier').length,
   substantiveDossiers:items.filter(i=>i.editorialStatus==='substantive_dossier').length
 },method:'Count documented chapters and distinct publishers. No automatic credibility or personality rating.',queue:items};
}
